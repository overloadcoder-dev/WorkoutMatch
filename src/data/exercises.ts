const reps = (
  beginner: number,
  intermediate: number,
  advanced: number,
  restSeconds = 45,
): Record<ExperienceLevel, RepetitionPrescription> => ({
  beginner: {
    mode: 'reps',
    sets: 2,
    reps: { min: Math.max(1, beginner - 2), max: beginner },
    restSeconds,
  },
  intermediate: {
    mode: 'reps',
    sets: 3,
    reps: { min: Math.max(5, intermediate - 2), max: intermediate },
    restSeconds: Math.max(20, restSeconds - 5),
  },
  advanced: {
    mode: 'reps',
    sets: 4,
    reps: { min: Math.max(6, advanced - 2), max: advanced },
    restSeconds: Math.max(15, restSeconds - 10),
  },
});

const timed = (
  beginner: number,
  intermediate: number,
  advanced: number,
  restSeconds = 30,
): Record<ExperienceLevel, TimePrescription> => ({
  beginner: { mode: 'time', sets: 2, workSeconds: beginner, restSeconds },
  intermediate: {
    mode: 'time',
    sets: 3,
    workSeconds: intermediate,
    restSeconds: Math.max(15, restSeconds - 5),
  },
  advanced: {
    mode: 'time',
    sets: 4,
    workSeconds: advanced,
    restSeconds: Math.max(10, restSeconds - 10),
  },
});

